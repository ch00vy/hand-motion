FINGER_QPOS_GROUPS = {
    "thumb": [3, 4, 5, 6],
    "index": [7, 9, 10],
    "middle": [11, 13, 14],
    "ring": [15, 17, 18],
    "pinky": [19, 21, 22],
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compare recorded qpos against forward qpos generated by estimated ctrl_ref."
    )
    parser.add_argument("--trial", required=True, help="Path to qpos.csv, legacy ctrl_est_*.csv, or trial directory.")
    parser.add_argument("--output-dir", default="artifacts/control_replay_qpos_comparison", help="Output directory.")
    parser.add_argument("--ctrl-ref-csv", default="", help="Optional explicit ctrl_ref CSV. Defaults to trial analysis artifact.")
    return parser.parse_args()


def _joint_names(model: Any, count: int) -> list[str]:
    try:
        import mujoco
    except Exception:
        return [f"qpos_{idx}" for idx in range(count)]
    raw_model = getattr(model, "ptr", model)
    names: list[str] = []
    for idx in range(count):
        try:
            name = mujoco.mj_id2name(raw_model, mujoco.mjtObj.mjOBJ_JOINT, int(idx)) or f"qpos_{idx}"
        except Exception:
            name = f"qpos_{idx}"
        names.append(str(name))
    return names


def _actuator_names(model: Any, count: int) -> list[str]:
    try:
        import mujoco
    except Exception:
        return [f"ctrl_{idx}" for idx in range(count)]
    raw_model = getattr(model, "ptr", model)
    names: list[str] = []
    for idx in range(count):
        try:
            name = mujoco.mj_id2name(raw_model, mujoco.mjtObj.mjOBJ_ACTUATOR, int(idx)) or f"ctrl_{idx}"
        except Exception:
            name = f"ctrl_{idx}"
        names.append(str(name))
    return names


def _indexed_columns(columns: Any, prefixes: tuple[str, ...]) -> list[str]:
    for prefix in prefixes:
        indexed: list[tuple[int, str]] = []
        for name in columns:
            label = str(name)
            if not label.startswith(prefix):
                continue
            suffix = label[len(prefix) :]
            if suffix.isdigit():
                indexed.append((int(suffix), label))
        if indexed:
            return [label for _, label in sorted(indexed)]
    return []


def _load_ctrl_ref(trial_path: Path, explicit_csv: str) -> dict[str, Any]:
    trial = load_trial(trial_path)
    if explicit_csv:
        csv_path = Path(explicit_csv).resolve()
        df = pd.read_csv(csv_path)
        cols = _indexed_columns(df.columns, ("ctrl_ref_", "ctrl_teacher_", "ctrl_target_", "ctrl_"))
        if not cols:
            raise ValueError(f"No ctrl columns found in {csv_path}")
        ctrl = df[cols].apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0).to_numpy(float)
        if "frame_dt" in df.columns:
            dt_values = pd.to_numeric(df["frame_dt"], errors="coerce").to_numpy(float)
            dt_values = dt_values[np.isfinite(dt_values) & (dt_values > 0.0)]
            dt = float(np.median(dt_values)) if dt_values.size else float(trial.meta.get("dt") or 1.0 / 60.0)
        else:
            dt = float(trial.meta.get("dt") or 1.0 / 60.0)
        return {
            "trial": trial,
            "ctrl_sequence": ctrl,
            "dt": dt,
            "source_path": csv_path,
            "quality": {},
        }
    out = BinaryGCNInferenceController().load_control_reference(trial)
    out["trial"] = trial
    return out


def _rollout_ctrl(trial: Any, ctrl_seq: np.ndarray, dt: float) -> tuple[np.ndarray, Any]:
    from myosuite.utils import gym

    env = gym.make("myoHandPoseRandom-v0")
    env = env.unwrapped
    model = env.sim.model
    data = env.sim.data
    qpos_recorded = np.asarray(trial.qpos, dtype=float)
    ctrl_seq = np.asarray(ctrl_seq, dtype=float)
    frame_count = min(int(qpos_recorded.shape[0]), int(ctrl_seq.shape[0]))
    if frame_count <= 0:
        raise ValueError("Empty qpos/control sequence.")

    full_qpos = np.zeros(int(model.nq), dtype=float)
    full_qpos[: min(len(full_qpos), qpos_recorded.shape[1])] = qpos_recorded[0, : min(len(full_qpos), qpos_recorded.shape[1])]
    data.qpos[:] = full_qpos
    data.qvel[:] = 0.0
    if hasattr(data, "qacc"):
        data.qacc[:] = 0.0
    data.ctrl[:] = 0.0
    if hasattr(data, "act") and len(data.act):
        data.act[:] = 0.0
    env.sim.forward()

    timestep = float(model.opt.timestep)
    substeps = max(1, int(round(float(dt) / max(timestep, 1e-8))))
    forward_rows = [np.asarray(data.qpos, dtype=float).copy()]
    for idx in range(frame_count - 1):
        ctrl = np.asarray(ctrl_seq[idx], dtype=float).reshape(-1)
        data.ctrl[:] = 0.0
        data.ctrl[: min(len(ctrl), int(data.ctrl.shape[0]))] = ctrl[: min(len(ctrl), int(data.ctrl.shape[0]))]
        for _ in range(substeps):
            env.sim.advance()
        forward_rows.append(np.asarray(data.qpos, dtype=float).copy())
    return np.asarray(forward_rows, dtype=float), env


def _finger_for_qpos(index: int) -> str:
    for finger, indices in FINGER_QPOS_GROUPS.items():
        if int(index) in indices:
            return finger
    return "other"


def _write_report(
    path: Path,
    *,
    trial: Any,
    ctrl_source: Path,
    summary: dict[str, Any],
    worst_joints: pd.DataFrame,
    finger_summary: pd.DataFrame,
    ctrl_summary: pd.DataFrame,
) -> None:
    def simple_markdown(df: pd.DataFrame) -> str:
        if df.empty:
            return "_empty_"
        headers = [str(col) for col in df.columns]
        lines_out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
        for row in df.astype(object).where(pd.notnull(df), "").values.tolist():
            lines_out.append("| " + " | ".join(str(item) for item in row) + " |")
        return "\n".join(lines_out)

    lines = [
        "# Control Replay vs Recorded Qpos Comparison",
        "",
        f"- Trial: `{trial.trial_id}`",
        f"- Motion type: `{trial.motion_type}`",
        f"- Recorded qpos: `{trial.qpos_csv}`",
        f"- ctrl_ref: `{ctrl_source}`",
        "",
        "## Summary",
        "",
    ]
    for key, value in summary.items():
        if isinstance(value, float):
            lines.append(f"- `{key}`: `{value:.6f}`")
        else:
            lines.append(f"- `{key}`: `{value}`")
    lines.extend(["", "## Worst Joints", "", simple_markdown(worst_joints)])
    lines.extend(["", "## Finger Summary", "", simple_markdown(finger_summary)])
    lines.extend(["", "## Strongest Controls", "", simple_markdown(ctrl_summary.head(12))])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    out_dir = Path(args.output_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    ctrl_payload = _load_ctrl_ref(Path(args.trial), str(args.ctrl_ref_csv or ""))
    trial = ctrl_payload["trial"]
    ctrl_seq = np.asarray(ctrl_payload["ctrl_sequence"], dtype=float)
    dt = float(ctrl_payload["dt"])
    qpos_forward, env = _rollout_ctrl(trial, ctrl_seq, dt)
    model = env.sim.model
    qpos_recorded = np.asarray(trial.qpos[: qpos_forward.shape[0]], dtype=float)
    n_qpos = min(qpos_forward.shape[1], qpos_recorded.shape[1])
    qpos_forward = qpos_forward[:, :n_qpos]
    qpos_recorded = qpos_recorded[:, :n_qpos]
    error = qpos_forward - qpos_recorded
    joint_names = _joint_names(model, n_qpos)

    frame_rows: list[dict[str, Any]] = []
    for frame_idx in range(qpos_forward.shape[0]):
        row: dict[str, Any] = {
            "frame_index": int(frame_idx),
            "progress_percent": float(100.0 * frame_idx / max(1, qpos_forward.shape[0] - 1)),
            "qpos_error_norm": float(np.linalg.norm(error[frame_idx])),
            "qpos_rmse": float(np.sqrt(np.mean(error[frame_idx] ** 2))),
            "qpos_mae": float(np.mean(np.abs(error[frame_idx]))),
        }
        for finger, indices in FINGER_QPOS_GROUPS.items():
            valid = [idx for idx in indices if idx < n_qpos]
            if valid:
                row[f"{finger}_rmse"] = float(np.sqrt(np.mean(error[frame_idx, valid] ** 2)))
        frame_rows.append(row)
    frame_df = pd.DataFrame(frame_rows)

    joint_rows: list[dict[str, Any]] = []
    for idx in range(n_qpos):
        err = error[:, idx]
        joint_rows.append(
            {
                "qpos_index": int(idx),
                "joint_name": joint_names[idx],
                "finger": _finger_for_qpos(idx),
                "recorded_start": float(qpos_recorded[0, idx]),
                "recorded_end": float(qpos_recorded[-1, idx]),
                "forward_end": float(qpos_forward[-1, idx]),
                "final_error": float(qpos_forward[-1, idx] - qpos_recorded[-1, idx]),
                "rmse": float(np.sqrt(np.mean(err ** 2))),
                "mae": float(np.mean(np.abs(err))),
                "max_abs_error": float(np.max(np.abs(err))),
            }
        )
    joint_df = pd.DataFrame(joint_rows).sort_values("rmse", ascending=False)

    finger_rows: list[dict[str, Any]] = []
    for finger, indices in FINGER_QPOS_GROUPS.items():
        valid = [idx for idx in indices if idx < n_qpos]
        if not valid:
            continue
        err = error[:, valid]
        finger_rows.append(
            {
                "finger": finger,
                "num_qpos": int(len(valid)),
                "rmse": float(np.sqrt(np.mean(err ** 2))),
                "mae": float(np.mean(np.abs(err))),
                "final_rmse": float(np.sqrt(np.mean(error[-1, valid] ** 2))),
                "final_error_norm": float(np.linalg.norm(error[-1, valid])),
            }
        )
    finger_df = pd.DataFrame(finger_rows).sort_values("rmse", ascending=False)

    actuator_names = _actuator_names(model, int(ctrl_seq.shape[1]))
    ctrl_rows: list[dict[str, Any]] = []
    for idx in range(int(ctrl_seq.shape[1])):
        values = ctrl_seq[:, idx]
        ctrl_rows.append(
            {
                "ctrl_index": int(idx),
                "actuator_name": actuator_names[idx] if idx < len(actuator_names) else f"ctrl_{idx}",
                "mean_ctrl": float(np.mean(values)),
                "max_ctrl": float(np.max(values)),
                "active_fraction_gt_0_01": float(np.mean(values > 0.01)),
                "active_fraction_gt_0_05": float(np.mean(values > 0.05)),
            }
        )
    ctrl_df = pd.DataFrame(ctrl_rows).sort_values(["max_ctrl", "mean_ctrl"], ascending=False)

    summary = {
        "trial_id": str(trial.trial_id),
        "motion_type": str(trial.motion_type),
        "num_frames_compared": int(qpos_forward.shape[0]),
        "num_qpos_compared": int(n_qpos),
        "ctrl_source": str(ctrl_payload["source_path"]),
        "dt": float(dt),
        "overall_qpos_rmse": float(np.sqrt(np.mean(error ** 2))),
        "overall_qpos_mae": float(np.mean(np.abs(error))),
        "final_qpos_rmse": float(np.sqrt(np.mean(error[-1] ** 2))),
        "final_qpos_error_norm": float(np.linalg.norm(error[-1])),
        "worst_finger_by_rmse": str(finger_df.iloc[0]["finger"]) if not finger_df.empty else "",
        "worst_joint_by_rmse": str(joint_df.iloc[0]["joint_name"]) if not joint_df.empty else "",
    }
    quality = dict(ctrl_payload.get("quality") or {})
    for key in ("rmse_forward_error", "mean_joint_error", "relative_residual_mean", "ctrl_norm_mean"):
        if key in quality:
            try:
                summary[f"ctrl_ref_{key}"] = float(quality[key])
            except Exception:
                pass

    frame_df.to_csv(out_dir / "per_frame_qpos_mismatch.csv", index=False)
    joint_df.to_csv(out_dir / "per_joint_qpos_mismatch.csv", index=False)
    finger_df.to_csv(out_dir / "per_finger_qpos_mismatch.csv", index=False)
    ctrl_df.to_csv(out_dir / "ctrl_ref_summary.csv", index=False)
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    _write_report(
        out_dir / "control_replay_qpos_mismatch_report.md",
        trial=trial,
        ctrl_source=Path(str(ctrl_payload["source_path"])),
        summary=summary,
        worst_joints=joint_df.head(12),
        finger_summary=finger_df,
        ctrl_summary=ctrl_df,
    )
    print(f"[COMPARE] wrote {out_dir}")
    print(json.dumps(summary, indent=2))
    try:
        env.close()
    except Exception:
        pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
